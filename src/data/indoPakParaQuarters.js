export default indoPakParaQuarters;

export function getIndoPakParaQuarterTargets(juzNumber) {
  return indoPakParaQuarters[Number(juzNumber)] || indoPakParaQuarters[1];
}

export function getCurrentIndoPakJuzProgress(page, surah, ayah, juzNumber) {
  const targets = getIndoPakParaQuarterTargets(juzNumber);
  const current = {
    page: Number(page) || 1,
    surah: Number(surah) || 1,
    ayah: Number(ayah) || 1,
  };
  const quarter1 = targets.find((target) => target.id === 'quarter1');
  const half = targets.find((target) => target.id === 'half');
  const quarter3 = targets.find((target) => target.id === 'quarter3');

  if (quarter3 && comparePosition(current, quarter3) >= 0) return 'Q4';
  if (half && comparePosition(current, half) >= 0) return 'Q3';
  if (quarter1 && comparePosition(current, quarter1) >= 0) return 'Q2';
  return 'Q1';
}

function comparePosition(current, marker) {
  if (current.page !== Number(marker.page)) {
    return current.page - Number(marker.page);
  }
  if (current.surah !== Number(marker.surah)) {
    return current.surah - Number(marker.surah);
  }
  return current.ayah - Number(marker.ayah);
}
